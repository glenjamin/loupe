import Foundation

/// Linguist's rules for telling generated code by its first lines, ported from
/// `lib/linguist/generated.rb` at the release `Resources/linguist/VERSION` names. Each reads only
/// as many lines from the top of a file as Linguist's does; rules that need the whole file or its
/// last lines aren't ported, so a file only they would catch stays in the review.
public enum GeneratedCode {
    /// How many of its first lines a file at `path` must be read to, for the rules its name
    /// brings in; nil when none does, so its content needn't be read at all.
    public static func linesNeeded(forPath path: String) -> Int? {
        let file = FileName(path)
        return rules.filter { $0.applies(file) }.map(\.lines).max()
    }

    /// Whether Linguist takes the file at `path` for generated code, given its first lines:
    /// the text up to and including the line `linesNeeded(forPath:)` asks for, or all of it.
    public static func isGenerated(path: String, head: String) -> Bool {
        let file = FileName(path)
        // As Ruby's `data.split("\n", -1)`: an empty file has no lines, a trailing newline leaves an empty last one.
        let lines = head.isEmpty ? [] : head.split(separator: "\n", omittingEmptySubsequences: false)
        return rules.contains { $0.applies(file) && $0.matches(lines) }
    }

    /// Linguist's content rules, each named for its method in `generated.rb`. `lines` covers both
    /// the lines a rule reads and its `lines.count > n` guard, which needs a line past the n-th.
    private static let rules: [Rule] = [
        Rule("generated_go?", extensions: [".go"], lines: 40) { lines in
            lines.count > 1 && lines.prefix(40).contains { $0.hasPrefix("// Code generated ") }
        },
        Rule("generated_protocol_buffer_from_go?", extensions: [".proto"], lines: 20) { lines in
            lines.count > 1 && lines.prefix(20).contains { $0.contains("This file was autogenerated by go-to-protobuf") }
        },
        Rule("generated_protocol_buffer?", extensions: [".py", ".java", ".h", ".cc", ".cpp", ".m", ".rb", ".php"], lines: 3) { lines in
            lines.count > 1 && lines.prefix(3).contains { $0.contains("Generated by the protocol buffer compiler.  DO NOT EDIT!") }
        },
        Rule("generated_javascript_protocol_buffer?", extensions: [".js"], lines: 7) { lines in
            lines.count > 6 && lines[5].contains("GENERATED CODE -- DO NOT EDIT!")
        },
        Rule("generated_typescript_protocol_buffer?", extensions: [".ts"], lines: 5) { lines in
            lines.count > 4 && lines[0].contains("Code generated by protoc-gen-ts_proto. DO NOT EDIT.")
        },
        Rule("generated_twirp_ruby?", extensions: [".rb"], lines: 3) { lines in
            lines.count > 1 && lines.prefix(3).contains { $0.contains("Code generated by protoc-gen-twirp_ruby") && $0.contains("DO NOT EDIT.") }
        },
        Rule("generated_apache_thrift?", extensions: [".rb", ".py", ".go", ".js", ".m", ".java", ".h", ".cc", ".cpp", ".php"], lines: 6) { lines in
            lines.prefix(6).contains { $0.contains("Autogenerated by Thrift Compiler") }
        },
        Rule("generated_jni_header?", extensions: [".h"], lines: 3) { lines in
            lines.count > 2 && lines[0].contains("/* DO NOT EDIT THIS FILE - it is machine generated */") && lines[1].contains("#include <jni.h>")
        },
        // Only its first-line test; the module-closure scoring reads the whole file.
        Rule("compiled_coffeescript?", extensions: [".js"], lines: 1) { lines in
            lines.first?.hasPrefix("// Generated by ") == true
        },
        Rule("generated_parser?", extensions: [".js"], lines: 5) { lines in
            matches(pegJS, lines.prefix(5).joined())
        },
        Rule("source_map?", extensions: [".map"], ignoringCase: true, lines: 1) { lines in
            guard let first = lines.first else { return false }
            return matches(sourceMapV2, first) || first.hasPrefix("/** Begin line maps. **/{")
        },
        Rule("generated_antlr?", extensions: [".g"], lines: 3) { lines in
            lines.count > 2 && lines[1].contains("generated by Xtest")
        },
        Rule("compiled_cython_file?", extensions: [".c", ".cpp"], lines: 2) { lines in
            lines.count > 1 && lines[0].contains("Generated by Cython")
        },
        Rule("generated_module?", extensions: [".mod"], lines: 2) { lines in
            lines.count > 1 && (lines[0].contains("PCBNEW-LibModule-V") || lines[0].contains("GFORTRAN module version '"))
        },
        Rule("generated_unity3d_meta?", extensions: [".meta"], lines: 2) { lines in
            lines.count > 1 && lines[0].contains("fileFormatVersion: ")
        },
        Rule("generated_racc?", extensions: [".rb"], lines: 3) { lines in
            lines.count > 2 && lines[2].hasPrefix("# This file is automatically generated by Racc")
        },
        Rule("generated_jflex?", extensions: [".java"], lines: 2) { lines in
            lines.count > 1 && lines[0].hasPrefix("/* The following code was generated by JFlex ")
        },
        Rule("generated_grammarkit?", extensions: [".java"], lines: 2) { lines in
            lines.count > 1 && lines[0].hasPrefix("// This is a generated file. Not intended for manual editing.")
        },
        Rule("generated_roxygen2?", extensions: [".Rd"], lines: 2) { lines in
            lines.count > 1 && lines[0].contains("% Generated by roxygen2: do not edit by hand")
        },
        Rule("generated_jison?", extensions: [".js"], lines: 2) { lines in
            lines.count > 1 && (lines[0].hasPrefix("/* parser generated by jison ") || lines[0].hasPrefix("/* generated by jison-lex "))
        },
        Rule("generated_grpc_cpp?", extensions: [".cpp", ".hpp", ".h", ".cc"], lines: 2) { lines in
            lines.count > 1 && lines[0].hasPrefix("// Generated by the gRPC")
        },
        Rule("generated_dart?", extensions: [".dart"], lines: 3) { lines in
            lines.count > 1 && lines.prefix(3).contains { matches(dartHeader, $0.lowercased()) }
        },
        Rule("generated_perl_ppport_header?", named: { $0.path.hasSuffix("ppport.h") }, lines: 11) { lines in
            lines.count > 10 && lines[8].contains("Automatically created by Devel::PPPort")
        },
        Rule("generated_gamemakerstudio?", extensions: [".yy", ".yyp"], lines: 4) { lines in
            lines.count > 3 && (matches(gameMakerJSON, lines.prefix(3).joined()) || matches(gameMakerVersion, lines[0]))
        },
        Rule("generated_gimp?", extensions: [".c", ".h"], lines: 1) { lines in
            guard let first = lines.first else { return false }
            return matches(gimpSource, first) || matches(gimpHeader, first)
        },
        Rule("generated_visualstudio6?", extensions: [".dsp"], ignoringCase: true, lines: 3) { lines in
            lines.prefix(3).contains { $0.contains("# Microsoft Developer Studio Generated Build File") }
        },
        Rule("generated_haxe?", extensions: [".js", ".py", ".lua", ".cpp", ".h", ".java", ".cs", ".php"], lines: 3) { lines in
            lines.prefix(3).contains { $0.contains("Generated by Haxe") }
        },
        Rule("generated_html?", extensions: [".html", ".htm", ".xhtml"], ignoringCase: true, lines: 31) { lines in
            guard lines.count > 1 else { return false }
            if lines.prefix(2).contains(where: { $0.contains("<!-- Generated by pkgdown: do not edit by hand -->") }) { return true }
            if lines.count > 2 && lines[2].hasPrefix("<!-- This is an automatically generated file.") { return true }
            if lines.prefix(31).contains(where: { matches(doxygen, $0) }) { return true }
            return htmlMetaNamesGenerator(lines.prefix(31).joined(separator: " "))
        },
        Rule("generated_jooq?", extensions: [".java"], ignoringCase: true, lines: 2) { lines in
            lines.prefix(2).contains { $0.contains("This file is generated by jOOQ.") }
        },
        Rule("generated_sorbet_rbi?", extensions: [".rbi"], ignoringCase: true, lines: 5) { lines in
            lines.count >= 5 && lines[0].hasPrefix("# typed:") && lines[2].contains("DO NOT EDIT MANUALLY") && matches(tapioca, lines[4])
        },
        Rule("generated_mysql_view_definition_format?", extensions: [".frm"], ignoringCase: true, lines: 1) { lines in
            lines.first?.contains("TYPE=VIEW") == true
        },
    ]
}

/// One of Linguist's content rules: which files it looks at, how many of their first lines it
/// reads, and its test of those lines.
private struct Rule: Sendable {
    let name: String
    let applies: @Sendable (FileName) -> Bool
    let lines: Int
    let matches: @Sendable ([Substring]) -> Bool

    /// A rule for files with one of `extensions`, as Ruby's `File.extname` gives it: compared
    /// exactly, as Linguist mostly does, or lowercased where it calls `downcase`.
    init(_ name: String, extensions: Set<String>, ignoringCase: Bool = false, lines: Int, matches: @escaping @Sendable ([Substring]) -> Bool) {
        self.init(name, named: { extensions.contains(ignoringCase ? $0.extension.lowercased() : $0.extension) }, lines: lines, matches: matches)
    }

    init(_ name: String, named applies: @escaping @Sendable (FileName) -> Bool, lines: Int, matches: @escaping @Sendable ([Substring]) -> Bool) {
        self.name = name
        self.applies = applies
        self.lines = lines
        self.matches = matches
    }
}

/// A path and its extension as Ruby's `File.extname` finds it: from the last dot of the file
/// name, ignoring leading dots, so `.profile` has none and `a.pb.go` has `.go`.
private struct FileName: Sendable {
    let path: String
    let `extension`: String

    init(_ path: String) {
        self.path = path
        let name = path.split(separator: "/").last ?? path[...]
        let stem = name.drop { $0 == "." }
        self.extension = stem.lastIndex(of: ".").map { String(stem[$0...]) } ?? ""
    }
}

// Linguist's regexes, unchanged but for Ruby's `/` escapes. A line never holds a newline, so
// Ruby's line-anchored `^` means the start of the text here.
private let pegJS = regex(#"^(?:[^/]|/[^*])*/\*(?:[^*]|\*[^/])*Generated by PEG.js"#)
private let sourceMapV2 = regex(#"^\{"version":\d+,"#)
private let dartHeader = regex(#"generated code\W{2,3}do not modify"#)
private let gameMakerJSON = regex(#"^\s*[\{\[]"#)
private let gameMakerVersion = regex(#"^\d\.\d\.\d.+\|\{"#)
private let gimpSource = regex(#"^/\* GIMP [a-zA-Z0-9\- ]+ C\-Source image dump \(.+?\.c\) \*/"#)
private let gimpHeader = regex(#"^/\*  GIMP header image file format \([a-zA-Z0-9\- ]+\)\: .+?\.h  \*/"#)
private let doxygen = regex(#"<!--\s+Generated by Doxygen\s+[.0-9]+\s*-->"#, options: .caseInsensitive)
private let tapioca = regex(#"^# Please (run|instead update this file by running) `bin/tapioca"#)
private let htmlMeta = regex(#"<meta(\s+[^>]++)>"#, options: .caseInsensitive)
private let htmlMetaAttribute = regex(#"(?:^|(?<=\s))(name|content|value)\s*=\s*("[^"]+"|'[^']+'|[^\s"']+)"#, options: .caseInsensitive)
private let htmlGenerators = regex(#"^(org\s+mode|j?latex2html|groff|makeinfo|texi2html|ronn)\b"#, options: .caseInsensitive)

/// Whether any `<meta>` tag in `text` names one of the generators Linguist knows, as its
/// `generated_html?` and `extract_html_meta` read them.
private func htmlMetaNamesGenerator(_ text: String) -> Bool {
    let tags = htmlMeta.matches(in: text, range: NSRange(text.startIndex..., in: text))
    return tags.contains { tag in
        guard let range = Range(tag.range(at: 1), in: text) else { return false }
        var attributes = String(text[range])
        if attributes.hasSuffix("/") { attributes.removeLast() }
        attributes = attributes.trimmingCharacters(in: .whitespaces)
        var pairs: [String: String] = [:]
        for match in htmlMetaAttribute.matches(in: attributes, range: NSRange(attributes.startIndex..., in: attributes)) {
            guard let key = Range(match.range(at: 1), in: attributes), let value = Range(match.range(at: 2), in: attributes) else { continue }
            pairs[attributes[key].lowercased()] = unquoted(attributes[value])
        }
        guard pairs["name"]?.lowercased() == "generator" else { return false }
        return [pairs["content"], pairs["value"]].compactMap { $0 }.contains { matches(htmlGenerators, $0) }
    }
}

/// An attribute value less one leading and one trailing quote, as Linguist strips them.
private func unquoted(_ value: Substring) -> String {
    var value = value
    if let first = value.first, "\"'".contains(first) { value = value.dropFirst() }
    if let last = value.last, "\"'".contains(last) { value = value.dropLast() }
    return String(value)
}

private func matches(_ regex: NSRegularExpression, _ text: some StringProtocol) -> Bool {
    let text = String(text)
    return regex.firstMatch(in: text, range: NSRange(text.startIndex..., in: text)) != nil
}

private func regex(_ pattern: String, options: NSRegularExpression.Options = []) -> NSRegularExpression {
    // The patterns are fixed, so one that fails to compile is a bug here, caught by the tests.
    try! NSRegularExpression(pattern: pattern, options: options)
}
