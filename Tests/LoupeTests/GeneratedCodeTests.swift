import LoupeCore
import Testing

struct GeneratedCodeTests {
    @Test func hidesGeneratedCodeByItsFirstLinesAsGitHubDoes() {
        let generated: [(path: String, head: String)] = [
            ("api/service.pb.go", "// Code generated by protoc-gen-go. DO NOT EDIT.\n// versions:\n"),
            ("mocks/store.go", "// Package mocks is a mock.\n//\n// Code generated by MockGen. DO NOT EDIT.\npackage mocks\n"),
            ("api/service_pb2.py", "# -*- coding: utf-8 -*-\n# Generated by the protocol buffer compiler.  DO NOT EDIT!\n"),
            ("api/service.pb.h", "// Generated by the protocol buffer compiler.  DO NOT EDIT!\n// source: service.proto\n"),
            ("api/service.grpc.pb.cc", "// Generated by the gRPC C++ plugin.\n// If you make any local change, they will be lost.\n"),
            ("web/service.ts", "// Code generated by protoc-gen-ts_proto. DO NOT EDIT.\n// versions:\n//   protoc-gen-ts_proto  v1.181.2\n// source: hello.proto\n\n"),
            ("web/service_grpc_pb.js", "// a\n// b\n// c\n// d\n// e\n// GENERATED CODE -- DO NOT EDIT!\n\n"),
            ("lib/model.g.dart", "// GENERATED CODE - DO NOT MODIFY BY HAND\n\npart of 'model.dart';\n"),
            ("rpc/service_twirp.rb", "# Code generated by protoc-gen-twirp_ruby 1.14.1, DO NOT EDIT.\nrequire 'twirp'\n"),
            ("web/parser.js", "/* parser generated by jison 0.4.18 */\nvar parser = {};\n"),
            ("docs/tool.1.html", "<html>\n<head><meta name=\"generator\" content=\"groff -Thtml\"></head>\n"),
        ]
        for file in generated {
            #expect(PathFilter.default.excludes(file.path, head: file.head), "\(file.path) should be hidden")
        }
    }

    @Test func keepsCodeThatOnlyLooksGenerated() {
        let kept: [(path: String, head: String)] = [
            ("api/service.go", "package api\n\n// Code here is written by hand.\n"),
            // Linguist wants more than one line, and reads only the first 40.
            ("api/one.go", "// Code generated by hand"),
            ("api/late.go", String(repeating: "//\n", count: 40) + "// Code generated by protoc-gen-go. DO NOT EDIT.\n"),
            // A rule only applies to the extensions Linguist gives it: it has none for Swift.
            ("Sources/Service.pb.swift", "// DO NOT EDIT.\n// swift-format-ignore-file\n// Generated by the Swift generator plugin for the protocol buffer compiler.\n"),
            ("api/service.rs", "// Generated by the protocol buffer compiler.  DO NOT EDIT!\n\n"),
        ]
        for file in kept {
            #expect(!PathFilter.default.excludes(file.path, head: file.head), "\(file.path) should be kept")
        }
    }

    @Test func readsOnlyTheLinesLinguistsRulesForAPathLookAt() {
        let filter = PathFilter.default
        #expect(filter.linesNeeded(toDecide: "api/service.pb.go") == 40)
        #expect(filter.linesNeeded(toDecide: "api/service_pb2.py") == 6, "the protobuf rule reads 3, Thrift's 6")
        #expect(filter.linesNeeded(toDecide: "web/index.html") == 31)
        #expect(filter.linesNeeded(toDecide: "README.md") == nil)
        // Already decided by its path or its attributes, so never read.
        #expect(filter.linesNeeded(toDecide: "vendor/example.com/lib/lib.go") == nil)
        #expect(filter.linesNeeded(toDecide: "api/service.pb.go", attributes: LinguistAttributes(generated: false)) == nil)
        #expect(filter.linesNeeded(toDecide: "api/service.pb.go", attributes: LinguistAttributes(generated: true)) == nil)
    }

    @Test func letsGitAttributesOverrideTheContentRules() {
        let head = "// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage api\n"
        #expect(!PathFilter.default.excludes("api/service.pb.go", attributes: LinguistAttributes(generated: false), head: head))
        #expect(PathFilter.default.excludes("api/service.go", attributes: LinguistAttributes(generated: true), head: "package api\n"))
    }
}
